import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises'
import { dirname, extname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const patchesRoot = join(projectRoot, 'src', 'patches')
const generatedRoot = join(projectRoot, 'src', 'generated')
const ID_PATTERN = /^[a-z][a-z0-9-]*$/

function assertString(value, field, manifestPath) {
  if (typeof value !== 'string' || value.trim() === '') throw new Error(`${manifestPath}: ${field} must be a non-empty string`)
  return value
}

async function assertFile(path, field, manifestPath) {
  if (!(await stat(path).catch(() => undefined))?.isFile()) throw new Error(`${manifestPath}: ${field} entry does not exist: ${path}`)
}

function assertPatchLocal(path, patchDirectory, field, manifestPath) {
  const within = relative(patchDirectory, path)
  if (within === '..' || within.startsWith(`..${sep}`) || isAbsolute(within)) {
    throw new Error(`${manifestPath}: ${field} entry must stay inside its patch directory`)
  }
}

function moduleSpecifier(fromDirectory, absoluteEntry) {
  const withoutExtension = absoluteEntry.slice(0, -extname(absoluteEntry).length)
  let specifier = relative(fromDirectory, withoutExtension).split(sep).join('/')
  if (!specifier.startsWith('.')) specifier = `./${specifier}`
  return `${specifier}.js`
}

function identifier(id) {
  return id.replace(/-([a-z0-9])/g, (_match, char) => char.toUpperCase())
}

async function readCatalog() {
  const directories = (await readdir(patchesRoot, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
  const catalog = []
  for (const directory of directories) {
    const manifestPath = join(patchesRoot, directory, 'patch.json')
    const raw = await readFile(manifestPath, 'utf8').catch(() => undefined)
    if (raw === undefined) throw new Error(`${directory}: missing patch.json`)
    let manifest
    try {
      manifest = JSON.parse(raw)
    } catch (error) {
      throw new Error(`${manifestPath}: invalid JSON`, { cause: error })
    }
    const id = assertString(manifest.id, 'id', manifestPath)
    if (id !== directory || !ID_PATTERN.test(id)) throw new Error(`${manifestPath}: id must equal directory and match ${String(ID_PATTERN)}`)
    const name = assertString(manifest.name, 'name', manifestPath)
    const description = assertString(manifest.description, 'description', manifestPath)
    if (typeof manifest.defaultEnabled !== 'boolean') throw new Error(`${manifestPath}: defaultEnabled must be boolean`)
    if (!Number.isSafeInteger(manifest.order)) throw new Error(`${manifestPath}: order must be a safe integer`)
    const hostRelative = assertString(manifest.host, 'host', manifestPath)
    const client = manifest.client
    if (typeof client !== 'object' || client === null || Array.isArray(client)) throw new Error(`${manifestPath}: client must be an object`)
    if (client.kind !== 'message-action' && client.kind !== 'standalone') throw new Error(`${manifestPath}: client.kind must be message-action or standalone`)
    const clientRelative = assertString(client.entry, 'client.entry', manifestPath)
    const host = resolve(patchesRoot, directory, hostRelative)
    const clientEntry = resolve(patchesRoot, directory, clientRelative)
    assertPatchLocal(host, join(patchesRoot, directory), 'host', manifestPath)
    assertPatchLocal(clientEntry, join(patchesRoot, directory), 'client.entry', manifestPath)
    await assertFile(host, 'host', manifestPath)
    await assertFile(clientEntry, 'client.entry', manifestPath)
    catalog.push({ id, name, description, defaultEnabled: manifest.defaultEnabled, order: manifest.order, host, client: clientEntry, clientKind: client.kind })
  }
  const ids = new Set()
  const orders = new Set()
  for (const patch of catalog) {
    if (ids.has(patch.id)) throw new Error(`duplicate patch id: ${patch.id}`)
    if (orders.has(patch.order)) throw new Error(`duplicate patch order: ${String(patch.order)}`)
    ids.add(patch.id)
    orders.add(patch.order)
  }
  return catalog.sort((left, right) => left.order - right.order || left.id.localeCompare(right.id))
}

function generateCatalog(catalog) {
  const rows = catalog.map(({ id, name, description, defaultEnabled, order, clientKind }) => {
    return `  ${JSON.stringify({ id, name, description, defaultEnabled, order, clientKind })},`
  }).join('\n')
  const fields = catalog.map(({ id }) => `  ${JSON.stringify(id)}: boolean`).join('\n')
  const defaults = catalog.map(({ id, defaultEnabled }) => `  ${JSON.stringify(id)}: ${String(defaultEnabled)},`).join('\n')
  return `/* Generated by scripts/generate-patch-registry.mjs. Do not edit. */
export const PATCH_CATALOG = [
${rows}
] as const

export type PatchId = typeof PATCH_CATALOG[number]['id']

export interface PatchSettings {
${fields}
}

export const DEFAULT_PATCH_SETTINGS: PatchSettings = {
${defaults}
}

export function decodePatchSettings(value: unknown): PatchSettings | undefined {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return undefined
  const candidate = value as Record<string, unknown>
  const decoded = { ...DEFAULT_PATCH_SETTINGS }
  for (const patch of PATCH_CATALOG) {
    const enabled = candidate[patch.id]
    if (enabled !== undefined && typeof enabled !== 'boolean') return undefined
    if (typeof enabled === 'boolean') decoded[patch.id] = enabled
  }
  return decoded
}
`
}

function generateHostSettingsSchema(catalog) {
  const schemaFields = catalog.map(({ id, defaultEnabled }) => `  ${JSON.stringify(id)}: z.boolean().default(${String(defaultEnabled)}),`).join('\n')
  return `/* Generated by scripts/generate-patch-registry.mjs. Host-only; do not edit. */
import z from '@deepseek-ai/schemastery'

export const PatchSettingsSchema = z.object({
${schemaFields}
})
`
}

function generateHostRegistry(catalog) {
  const imports = catalog.map((patch) => {
    return `import { hostPatch as ${identifier(patch.id)}HostPatch } from ${JSON.stringify(moduleSpecifier(generatedRoot, patch.host))}`
  }).join('\n')
  const items = catalog.map((patch) => `${identifier(patch.id)}HostPatch`).join(', ')
  return `/* Generated by scripts/generate-patch-registry.mjs. Do not edit. */
import type { HostPatch } from '../kernel/host/patch.js'
${imports}

export const HOST_PATCHES: readonly HostPatch[] = [${items}]
`
}

function generateClientRegistry(catalog) {
  const imports = catalog.map((patch) => {
    const exported = patch.clientKind === 'message-action' ? 'useMessageActions' : 'clientPatch'
    return `import { ${exported} as ${identifier(patch.id)}ClientPatch } from ${JSON.stringify(moduleSpecifier(generatedRoot, patch.client))}`
  }).join('\n')
  const actions = catalog.filter((patch) => patch.clientKind === 'message-action').map((patch) => {
    return `{ id: ${JSON.stringify(patch.id)}, order: ${String(patch.order)}, useActions: ${identifier(patch.id)}ClientPatch }`
  }).join(', ')
  const standalone = catalog.filter((patch) => patch.clientKind === 'standalone').map((patch) => `${identifier(patch.id)}ClientPatch`).join(', ')
  return `/* Generated by scripts/generate-patch-registry.mjs. Do not edit. */
import type { ClientPatch, MessageActionPatch } from '../kernel/client/patch.js'
${imports}

export const MESSAGE_ACTION_PATCHES: readonly MessageActionPatch[] = [${actions}]
export const CLIENT_PATCHES: readonly ClientPatch[] = [${standalone}]
`
}

const catalog = await readCatalog()
await mkdir(generatedRoot, { recursive: true })
await Promise.all([
  writeFile(join(generatedRoot, 'patch-catalog.ts'), generateCatalog(catalog), 'utf8'),
  writeFile(join(generatedRoot, 'host-settings-schema.ts'), generateHostSettingsSchema(catalog), 'utf8'),
  writeFile(join(generatedRoot, 'host-registry.ts'), generateHostRegistry(catalog), 'utf8'),
  writeFile(join(generatedRoot, 'client-registry.ts'), generateClientRegistry(catalog), 'utf8'),
])
process.stdout.write(`Generated ${String(catalog.length)} patch registrations.\n`)
